@router.callback_query(F.data.startswith("fp:"))
async def cb_fp(c: CallbackQuery, bot: Bot):
    parts = c.data.split(":", 2)
    if len(parts) != 3:
        await ack(c)
        return
    _, pid, act = parts
    p = polls.get(pid)
    if not p or p["chat"] != c.message.chat.id:
        await ack(c, "Это голосование уже закрыто.")
        await remove_keyboard(bot, c.message.chat.id, c.message.message_id)
        return
    uid, name = c.from_user.id, c.from_user.full_name
    if act == "end":
        await ack(c)
        await finish_poll(bot, p)
        return
    if act == "spin":
        if p["kind"] != "ship":
            await ack(c)
            return
        if len(p["cands"]) < 2:
            await ack(c, "Нужно минимум двое: нажмите «✋ Я участвую».", show_alert=True)
            return
        await ack(c)
        await send_msg(bot, p["chat"], ship_text(p["chat"], p["cands"]))
        return
    if act == "j":
        if any(u == uid for u, _ in p["cands"]):
            await ack(c, "Ты уже в списке 🙂")
            return
        if len(p["cands"]) >= FP_MAX_CANDS:
            await ack(c, "Список участников заполнен.")
            return
        p["cands"].append((uid, name))
        await ack(c, "Ты в списке ✅")
    elif act.startswith("v") and act[1:].isdigit():
        idx = int(act[1:])
        if idx >= len(poll_options(p)):
            await ack(c)
            return
        changed = uid in p["votes"]
        p["votes"][uid] = (idx, name)
        await ack(c, "Голос изменён ✅" if changed else "Голос принят ✅")
    else:
        await ack(c)
        return
    await edit_msg(c, poll_text(p), reply_markup=poll_kb(p))


