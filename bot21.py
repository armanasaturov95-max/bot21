_bot_username: str | None = None


async def bot_username(bot: Bot) -> str | None:
    """Имя бота (для ссылки «добавить в группу»). Запрашивается один раз."""
    global _bot_username
    if not _bot_username:
        try:
            _bot_username = (await bot.get_me()).username
        except Exception as e:
            logging.warning("Не удалось получить имя бота: %s", e)
    return _bot_username


def add_url(uname: str | None) -> str | None:
    return f"https://t.me/{uname}?startgroup=true" if uname else None


def home_kb(uname: str | None, private: bool):
    kb = InlineKeyboardBuilder()
    if private:
        if uname:
            kb.button(text="➕ Добавить в группу", url=add_url(uname))
        kb.button(text="📖 Как играть", callback_data="help:rules")
        kb.button(text="🎮 Команды", callback_data="help:cmds")
