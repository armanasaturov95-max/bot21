def load_settings() -> dict:
    try:
        with open(SETTINGS_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        return {}


def save_settings() -> None:
    with open(SETTINGS_FILE, "w", encoding="utf-8") as f:
        json.dump(settings, f, ensure_ascii=False)


settings: dict = load_settings()


def adult_enabled(chat_id: int) -> bool:
    return bool(settings.get(str(chat_id), {}).get("adult", False))


def _stat(chat_id: int, uid: int, name: str) -> dict:
    cfg = settings.setdefault(str(chat_id), {})
    entry = cfg.setdefault("stats", {}).setdefault(str(uid), {"name": name, "lost": 0, "caught": 0})
    entry["name"] = name
    entry.setdefault("lost", 0)
    entry.setdefault("caught", 0)
    return entry


def add_loss(chat_id: int, uid: int, name: str) -> None:
    _stat(chat_id, uid, name)["lost"] += 1
    save_settings()


def add_caught(chat_id: int, uid: int, name: str) -> None:
    _stat(chat_id, uid, name)["caught"] += 1
    save_settings()


def game_adult(g) -> bool:
    """18+ в игре включён, если он включён в чате (кнопка 🔞 или /mode18 — может любой)."""
    return adult_enabled(g.chat_id)


def allowed_cats(chat_id: int, adult: bool | None = None) -> list:
    if adult is None:
        adult = adult_enabled(chat_id)
    return ["fun", "love"] + (ADULT_CATS if adult else [])


def draw(chat_id: int, kind: str, category: str, adult: bool | None = None) -> str:
    """kind: 'q' — вопрос, 'd' — задание. adult=None — по настройке чата, иначе явно
    (в игре — включена ли кнопка 🔞). category 'adult' — случайный вопрос любого уровня 18+."""
    if adult is None:
        adult = adult_enabled(chat_id)
    if (category in ADULT_CATS or category == "adult") and not adult:
        category = "love"
    if category == "all":
        cats = allowed_cats(chat_id, adult)
    elif category == "adult":
        cats = ADULT_CATS
    else:
        cats = [category]
    key = (chat_id, kind, category, adult)
    if not _bags.get(key):
        src = QUESTIONS if kind == "q" else DARES
        bag = [t for c in cats for t in src[c]]
        random.shuffle(bag)
        _bags[key] = bag
    return _bags[key].pop()


def draw_penalty(chat_id: int, adult: bool | None = None) -> str:
    if adult is None:
        adult = adult_enabled(chat_id)
    key = (chat_id, "p", adult)
    if not _bags.get(key):
        bag = PENALTIES + (PENALTIES_HARD if adult else [])
        random.shuffle(bag)
        _bags[key] = bag
    return _bags[key].pop()


def cycle(seq: list, cur):
    try:
        return seq[(seq.index(cur) + 1) % len(seq)]
    except ValueError:
        return seq[0]


