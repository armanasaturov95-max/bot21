FP_TTL = 5 * 60          # голосование закрывается само через 5 минут
FP_MAX_CANDS = 20
polls: dict[str, dict] = {}


def draw_fp(chat_id: int, kind: str):
    adult = adult_enabled(chat_id)
    key = (chat_id, "fp", kind, adult)
    if not _bags.get(key):
        bag = list(FP_BANK[kind]) + (list(FP_BANK[kind + "18"]) if adult else [])
        random.shuffle(bag)
        _bags[key] = bag
    return _bags[key].pop()


def ship_text(chat_id: int, cands: list) -> str:
    (ua, na), (ub, nb) = random.sample(cands, 2)
    pct = random.randint(1, 100)
    verdict = next(v for lim, v in SHIP_VERDICTS if pct <= lim)
    hearts = round(pct / 10)
    bar = "❤️" * hearts + "🖤" * (10 - hearts)
    spicy = adult_enabled(chat_id) and pct >= 50
    task = random.choice(SHIP_TASKS18 if spicy else SHIP_TASKS)
    return (
        f"💘 {mention(ua, na)} + {mention(ub, nb)}\n\n"
        f"Совместимость: <b>{pct}%</b>\n{bar}\n\n{verdict}\n\n🎯 Задание паре: {task}"
    )


def poll_options(p: dict) -> list[str]:
    if p["kind"] == "ship":
        return []
    if p["kind"] == "wyr":
        return ["🅰️ Вариант А", "🅱️ Вариант Б"]
    if p["kind"] == "never":
        return ["🙋 Было", "🙅 Не было"]
    return [n for _, n in p["cands"]]


def poll_header(p: dict) -> str:
    if p["kind"] == "ship":
        return f"<b>{FP_KINDS['ship']}</b>\n\nСлучайно составим пару и покажем, насколько вы совместимы."
    item = p["item"]
    if p["kind"] == "wyr":
        return (
            f"<b>{FP_KINDS['wyr']}</b>\n\n"
            f"🅰️ {html.escape(item[0])}\n"
            f"<i>или</i>\n"
            f"🅱️ {html.escape(item[1])}"
        )
    return f"<b>{FP_KINDS[p['kind']]}</b>\n\n<b>{html.escape(item)}</b>"


def poll_text(p: dict) -> str:
    if p["kind"] == "ship":
        text = poll_header(p)
        if p["cands"]:
            text += "\n\n👥 Участники: " + ", ".join(html.escape(n) for _, n in p["cands"])
        else:
            text += "\n\nНажмите «✋ Я участвую», чтобы попасть в список."
        return text + "\n\n<i>Кнопку «💘 Выбрать пару» можно нажимать много раз. Игра закроется через 5 минут.</i>"
    text = poll_header(p) + f"\n\n🗳 Проголосовало: <b>{len(p['votes'])}</b>"
    if p["kind"] == "whom":
        if p["cands"]:
            text += "\n👥 Участники: " + ", ".join(html.escape(n) for _, n in p["cands"])
        else:
            text += "\n\nНажмите «✋ Я участвую», чтобы попасть в список."
    text += "\n\n<i>Итог — по кнопке или через 5 минут.</i>"
    return text


def poll_kb(p: dict):
    kb = InlineKeyboardBuilder()
    pid = p["id"]
    if p["kind"] == "ship":
        rows = []
        if len(p["cands"]) < FP_MAX_CANDS:
            kb.button(text="✋ Я участвую", callback_data=f"fp:{pid}:j")
            rows.append(1)
        kb.button(text="💘 Выбрать пару", callback_data=f"fp:{pid}:spin")
        kb.button(text="🏁 Закончить", callback_data=f"fp:{pid}:end")
        rows += [1, 1]
        kb.adjust(*rows)
        return kb.as_markup()
    opts = poll_options(p)
    for i, label in enumerate(opts):
        kb.button(text=label[:30], callback_data=f"fp:{pid}:v{i}")
    rows = [2] * (len(opts) // 2) + ([1] if len(opts) % 2 else [])
    if p["kind"] == "whom":
        if len(p["cands"]) < FP_MAX_CANDS:
            kb.button(text="✋ Я участвую", callback_data=f"fp:{pid}:j")
            rows.append(1)
    kb.button(text="🏁 Показать итог", callback_data=f"fp:{pid}:end")
    rows.append(1)
    kb.adjust(*rows)
    return kb.as_markup()


def poll_result_text(p: dict) -> str:
    if p["kind"] == "ship":
        return poll_header(p) + "\n\n🏁 Игра закончена. Спасибо!"
    opts = poll_options(p)
    total = len(p["votes"])
    lines = [poll_header(p), "", "📊 <b>Итоги</b>"]
    if total == 0:
        lines.append("Никто не проголосовал 🤷")
        return "\n".join(lines)
    by_opt: dict[int, list] = {}
    for uid, (idx, name) in p["votes"].items():
        by_opt.setdefault(idx, []).append((uid, name))
    order = sorted(range(len(opts)), key=lambda i: len(by_opt.get(i, [])), reverse=True)
    for i in order:
        voters = by_opt.get(i, [])
        if not voters and p["kind"] == "whom":
            continue
        pct = round(len(voters) * 100 / total)
        bar = "▓" * round(pct / 10) + "░" * (10 - round(pct / 10))
        lines.append(f"\n{html.escape(opts[i])} — <b>{len(voters)}</b> ({pct}%)\n{bar}")
        if voters and p["kind"] != "whom":
            lines.append(", ".join(mention(u, n) for u, n in voters))
    if p["kind"] == "whom":
        top = len(by_opt[order[0]])
        winners = [opts[i] for i in order if len(by_opt.get(i, [])) == top]
        lines.append("\n👑 Больше всех голосов: <b>" + ", ".join(html.escape(w) for w in winners) + "</b>")
    return "\n".join(lines)


async def finish_poll(bot: Bot, p: dict) -> None:
    if polls.pop(p["id"], None) is None:
        return
    t = p.get("task")
    if t and t is not asyncio.current_task():
        t.cancel()
    await safe_edit(bot, p["chat"], p["msg"], poll_result_text(p), None)


async def _poll_timer(bot: Bot, p: dict) -> None:
    try:
        await asyncio.sleep(FP_TTL)
    except asyncio.CancelledError:
        return
    await finish_poll(bot, p)


async def start_poll(m: Message, bot: Bot, kind: str) -> None:
    if not in_group(m):
        await m.answer("Эта игра работает в группе. Добавь меня в группу 🙂")
        return
    pid = f"{random.getrandbits(32):08x}"
    cands = []
    g = games.get(m.chat.id)
    if kind in ("whom", "ship") and g:
        cands = list(g.players)[:FP_MAX_CANDS]
    p = {"id": pid, "chat": m.chat.id, "msg": 0, "kind": kind, "item": "" if kind == "ship" else draw_fp(m.chat.id, kind),
         "votes": {}, "cands": cands, "task": None}
    msg = await m.answer(poll_text(p), reply_markup=poll_kb(p))
    p["msg"] = msg.message_id
    polls[pid] = p
    p["task"] = asyncio.create_task(_poll_timer(bot, p))


